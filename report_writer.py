from llm import llm


def generate_report(question, research_memory):
    """
    根据 Research Memory 生成最终行业研究报告。

    参数：
        question: 用户原始研究问题
        research_memory: Research Pipeline 生成的结构化研究记忆

    返回：
        Markdown 格式的研究报告
    """

    prompt = f"""
你是一名专业的行业研究报告撰写助手。

你的任务是：
根据已经完成的研究结果，生成一份结构清晰、
专业、可信、适合展示的行业研究报告。

注意：

你只能使用下面提供的 Research Memory 和 Citation Manager
中的信息。

严禁：
1. 编造不存在的数据。
2. 编造不存在的公司、政策、市场规模或技术事实。
3. 编造 URL。
4. 修改研究结果中的数字。
5. 把推测写成确定事实。
6. 使用你自己的外部知识补充研究资料。

如果现有研究资料不足以支持某个结论，
请明确写：

“现有资料不足，无法形成可靠结论。”

==================================================
用户研究问题
==================================================

{question}


==================================================
Research Memory
==================================================

{research_memory}


==================================================
报告生成要求
==================================================

一、报告必须使用 Markdown 格式。

二、报告标题：

# 新能源汽车行业研究报告

三、报告必须包含以下章节：

## 一、行业概况

介绍新能源汽车行业整体发展情况，
包括研究资料中能够支持的市场、产业和发展背景。

## 二、核心技术趋势

分析研究资料中涉及的：

- 动力电池
- 快充技术
- 固态电池
- 智能驾驶
- 智能座舱
- 充电基础设施
- 电动化
- 智能化
- 网联化

如果某一方向没有足够证据，不要强行扩展。

## 三、市场发展趋势

总结研究资料中关于：

- 市场规模
- 销量
- 渗透率
- 市场增长
- 区域市场

等方面的证据。

如果不同来源的数据存在差异，
必须明确说明存在数据差异，
不能自行选择一个数字作为“正确答案”。

## 四、竞争与产业趋势

根据现有研究结果分析：

- 企业竞争
- 产业链
- 全球化布局
- 技术竞争
- 成本竞争

如果研究资料没有足够证据，
明确说明资料不足。

## 五、未来发展机会

根据已有证据总结可能存在的：

- 市场机会
- 技术机会
- 产业链机会
- 全球化机会

注意：

“机会”必须建立在研究资料基础上，
不能凭空提出。

## 六、风险与挑战

总结研究资料中已经出现的：

- 政策风险
- 技术风险
- 成本风险
- 原材料风险
- 市场竞争风险
- 国际贸易或地缘政治风险

## 七、总结

用较简洁的方式总结整个研究结论。

==================================================
引用要求
==================================================

Research Memory 中包含 Citation Manager。

Citation Manager 中的 Evidence 都有唯一 ID，
例如：

T1-E1
T1-E2
T2-E1

如果一个结论来自某个 Evidence，
必须在结论后面标记对应的 Evidence ID。

格式：

新能源汽车行业正在向电动化、智能化和网联化方向发展。[T2-E1]

如果一个结论由多个 Evidence 支持：

新能源汽车市场仍保持增长趋势。[T1-E1][T1-E3]

注意：

1. 只能使用 Research Memory 中真实存在的 Evidence ID。
2. 不允许自己创造 Evidence ID。
3. 不允许创造 URL。
4. 不要直接把长 URL 写进正文。
5. 引用应该紧跟在对应事实或结论后面。
6. 如果没有 Evidence 支持，不要强行添加引用。


==================================================
写作要求
==================================================

1. 不要只是罗列资料，要进行分析。

2. 每个章节都应该有一定的逻辑结构。

3. 区分：
   - 已有研究事实
   - 基于研究事实得到的分析

4. 对存在争议的数据明确说明。

5. 对 Research Memory 中的 limitations 必须认真参考。

6. 不要隐藏研究失败、搜索失败或数据不足。

7. 报告应该像真正的行业研究报告，
   而不是简单的搜索结果汇总。

8. 输出内容只能是最终 Markdown 报告。

不要输出：

“好的”
“以下是报告”
“根据你的要求”
“我将为你……”

直接从：

# 新能源汽车行业研究报告

开始。


==================================================
开始生成报告
==================================================
"""

    response = llm.invoke(prompt)

    return response.content